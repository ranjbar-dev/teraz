export function pageTour(pathname: string, canWrite: boolean): TourStep[] {
  const [key, id, action] = pathname.split('/').filter(Boolean);
  const mod = modules.find((m) => m.key === key);
  if (mod) {
    const editor = id === 'new' || action === 'edit';
    const steps = [
      step(
        mod.title,
        `${mod.description}. ${workflows[key] || `برای شروع، اطلاعات ${mod.singular} را کامل و پیش از ذخیره بررسی کنید.`}`,
      ),
    ];
    if (editor) {
      steps.push(
        step(
          'تکمیل اطلاعات',
          `فیلدهای ستاره‌دار الزامی‌اند. اطلاعات اصلی این بخش: ${mod.fields
            .filter((f) => !f.hidden)
            .slice(0, 6)
            .map((f) => f.label)
            .join('، ')}. گزینه‌های مرتبط را می‌توانید جست‌وجو کنید.`,
          '.form-grid',
        ),
      );
      if (mod.kind)
        steps.push(
          step(
            'ردیف‌های سند',
            mod.kind === 'journal'
              ? 'حساب هر ردیف و بدهکار یا بستانکار آن را وارد کنید؛ تراز بودن جمع‌ها را بررسی کنید.'
              : 'اقلام، تعداد، قیمت، تخفیف و مالیات را تکمیل و جمع نهایی را بررسی کنید.',
            '.line-panel',
          ),
        );
      steps.push(
        step(
          'ذخیرهٔ فرم',
          'دکمهٔ ذخیره را پس از بازبینی بزنید. اگر خطایی نمایش داده شد، فیلد مربوط را اصلاح کنید. بستن راهنما تغییری در فرم ایجاد نمی‌کند.',
          '.form-action-bar',
        ),
      );
    } else if (id) {
      steps.push(
        step(
          'بازبینی جزئیات',
          'اطلاعات، وضعیت و ردیف‌های این رکورد را بررسی کنید. عملیات قابل انجام با وضعیت سند و نقش شما تغییر می‌کند.',
        ),
      );
      if (canWrite)
        steps.push(
          step(
            'عملیات سند',
            masterKeys.has(key)
              ? 'برای اصلاح اطلاعات از ویرایش استفاده کنید. پیش از حذف، وابستگی رکورد به سایر اطلاعات را بررسی کنید.'
              : 'پیش‌نویس را بازبینی و سپس ثبت قطعی کنید. سند قطعی قابل ویرایش یا حذف نیست؛ در صورت وجود گزینهٔ «ثبت سند برگشتی»، تاریخ و دلیل اصلاح را وارد کنید.',
            '.page-actions',
          ),
        );
      steps.push(
        step(
          'چاپ و پیوست‌ها',
          'در بخش‌هایی که چاپ یا پیوست دارند، از چاپ برای دریافت PDF مرورگر و از بخش پیوست برای مشاهده یا افزودن مدارک استفاده کنید.',
        ),
      );
    } else {
      if (canWrite)
        steps.push(
          step(
            `افزودن ${mod.singular}`,
            `از دکمهٔ افزودن بالای صفحه، فرم ${mod.singular} را باز کنید. ابتدا اطلاعات پایهٔ موردنیاز را تعریف کنید.`,
            '.page-actions',
          ),
        );
      steps.push(
        step(
          'جست‌وجو و فیلتر',
          'در جدول جست‌وجو کنید، فیلتر هر ستون را تنظیم کنید و با کلیک روی عنوان ستون مرتب‌سازی را تغییر دهید. در صورت وجود، زبانهٔ وضعیت را نیز انتخاب کنید.',
          '.table-toolbar',
        ),
      );
      steps.push(
        step(
          'جزئیات و خروجی',
          'رکورد موردنظر را برای مشاهدهٔ جزئیات باز کنید. دکمهٔ ستون‌ها نمایش فیلدها را تنظیم می‌کند؛ خروجی اکسل شامل ردیف‌های فیلترشده یا انتخاب‌شده است.',
          '.table-scroll',
        ),
      );
    }
    if (!canWrite)
      steps.push(
        step(
          'دسترسی مشاهده‌گر',
          'شما می‌توانید اطلاعات، گزارش‌ها و خروجی‌ها را بررسی کنید. برای ثبت یا ویرایش، مدیر سازمان باید دسترسی مناسب بدهد.',
        ),
      );
    return steps;
  }
  if (key === 'reports') {
    const report = reports.find((r) => r.key === id);
    return [
      step(
        report?.title || 'گزارش‌های مالی',
        report?.description ||
          'گزارش موردنظر را بر اساس سؤال خود انتخاب کنید؛ مانند سود و زیان، ماندهٔ حساب‌ها یا موجودی انبار.',
      ),
      step(
        'محدودهٔ گزارش',
        'شرکت، شعبه، سال مالی و فیلترهای تاریخ یا حساب را بررسی کنید. گزارش‌ها بر اساس اطلاعات ثبت‌شده در همین محدوده تهیه می‌شوند.',
        '.report-filters',
      ),
      step(
        'بررسی و دریافت خروجی',
        'نتیجه و جمع‌ها را مرور کنید؛ در گزارش‌های دارای جدول، فیلتر و مرتب‌سازی در دسترس است. از اکسل یا چاپ برای خروجی استفاده کنید.',
        '.page-actions',
      ),
    ];
  }
  return (
    services[key]?.steps || [
      step(
        'راهنمای صفحه',
        'از منوی اصلی بخش موردنظر را انتخاب کنید و راهنمای همان صفحه را اجرا کنید.',
      ),
    ]
  );
}

export function tourCatalog(admin: boolean) {
  return [
    ...Object.entries(services)
      .filter(([, s]) => !s.admin || admin)
      .map(([key, s]) => ({ path: '/' + key, title: s.title })),
    ...modules.filter((m) => !m.admin || admin).map((m) => ({ path: '/' + m.key, title: m.title })),
    ...reports.map((r) => ({ path: '/reports/' + r.key, title: r.title })),
  ];
}
